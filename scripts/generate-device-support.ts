#!/usr/bin/env node
/** Run with Node 24. Only this offline generator imports the executed audit runner. */
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { audit } from '../tests/content/coverage-runner.ts';
import type { Label } from '../tests/content/coverage-cases.ts';
import { SUPPORT_SECTIONS } from '../src/content/deviceSupport.ts';
import type { DeviceSupportData, SupportProbe, SupportSection, SupportStatus } from '../src/content/deviceSupport.ts';

export const generatedFile = new URL('../src/content/deviceSupport.generated.ts', import.meta.url);
const statuses = {
  functional: 'functional', partial: 'partial', 'display-only': 'display-only', unsupported: 'unsupported',
  'correct hardware rejection': 'hardware-rejection', 'ill-formed paper notation': 'ill-formed', unresolved: 'unresolved',
} as const satisfies Record<Label, SupportStatus>;

export function renderDeviceSupport(result = audit()): string {
  const models = Object.fromEntries(Object.entries(result.models).map(([id, { name, ios, networkLicense }]) => {
    assert.ok(ios, `Missing audited release for ${id}`);
    return [id, { name, ios, networkLicense }];
  })) as DeviceSupportData['models'];
  const evidence = new Map<string, number>();
  const byLine = new Map<number, SupportProbe[]>();
  for (const r of result.results) {
    assert.ok(!('error' in r), `${r.model}, L${r.line}, ${r.variant}: ${'error' in r ? r.error : ''}`);
    const index = evidence.get(r.proof) ?? evidence.size;
    evidence.set(r.proof, index);
    const fields = [r.model, statuses[r.label], r.outcome, r.variant, r.input, r.mode, index] as const;
    const probe: SupportProbe = r.blockedAt ? [...fields, [r.blockedAt, r.effectiveMode]] : fields;
    const probes = byLine.get(r.line) ?? [];
    probes.push(probe);
    byLine.set(r.line, probes);
  }
  const sources: DeviceSupportData['sources'] = result.sourceLines.filter((s) => s.kind === 'command').map((s) => {
    const probes = byLine.get(s.line);
    assert.ok(probes?.length && Object.hasOwn(SUPPORT_SECTIONS, s.section), `Missing section or probes for paper line ${s.line}`);
    return [s.section as SupportSection, s.page, s.line, s.lastLine, s.text.trim().replace(/\s+/g, ' '), probes];
  });
  assert.equal(sources.length, byLine.size, 'Every probe must have a paper reference');
  // One source row per physical reference, interned evidence, no fixtures, raw CLI output or setup scripts.
  return `// Generated by node scripts/generate-device-support.ts. Do not hand edit.
import type { DeviceSupportData } from './deviceSupport.ts';

export const DEVICE_SUPPORT: DeviceSupportData = {
  source: ${JSON.stringify(result.source)},
  models: ${JSON.stringify(models)},
  evidence: ${JSON.stringify([...evidence.keys()])},
  sources: [\n${sources.map((source) => `    ${JSON.stringify(source)},`).join('\n')}
  ],
};
`;
}

if (import.meta.main) writeFileSync(generatedFile, renderDeviceSupport());
