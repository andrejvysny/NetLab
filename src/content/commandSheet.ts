/**
 * The course command sheet shown in the Command sheet drawer.
 *
 * Sections A–G reproduce docs/course/cheat-sheet.txt (the paper the student may use in the real exam) line by line,
 * in the sheet's own notation (prompt + command + placeholders). Lines that wrap on paper are joined into one line.
 * Only obvious typos are fixed in `text`; every fix is mentioned in that line's `note`. Slovak remarks of the sheet are
 * kept as they are and translated in `note`. `warn` carries caveats from docs/HARDWARE_NOTES.md that apply to that line
 * on the exam hardware (ISR 4331 / Catalyst 9300L with IOS XE).
 * The last section is NOT on the paper sheet and says so in its title.
 */
import type { CommandSheetSection } from '../engine/labapi.ts';

type Line = CommandSheetSection['lines'][number];
const l = (text: string, note?: string, warn?: string): Line => {
  const line: Line = { text };
  if (note) line.note = note;
  if (warn) line.warn = warn;
  return line;
};

